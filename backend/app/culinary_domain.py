@lru_cache(maxsize=1)
def domain_graph():
    content = SOURCE.read_bytes()
    raw = yaml.safe_load(content.decode("utf-8-sig"))
    if set(raw) != {"archetypes", "base_ingredients", "cooking_methods", "recipe_paths"}:
        raise ValueError("Unexpected domain graph sections")
    if set(raw["archetypes"]) != set(ARCHETYPES) or len(raw["recipe_paths"]) != len(ACTIONS):
        raise ValueError("Every domain node requires adaptation")
    # Inspect YAML merge nodes before flattening so overrides retain their ancestry.
    document = yaml.compose(content.decode("utf-8-sig"))
    sections = {key.value: value for key, value in document.value}
    ancestor_nodes = {id(value): key.value for key, value in sections["archetypes"].value}
    inheritance = {}
    for key, node in sections["base_ingredients"].value:
        parents = [ancestor_nodes[id(value)] for field, value in node.value if field.value == "<<"]
        if len(parents) != 1:
            raise ValueError("Expected one explicit ingredient archetype")
        inheritance[ID_MAP.get(key.value, key.value)] = parents[0]
    paths = []
    for index, entry in enumerate(raw["recipe_paths"]):
        ingredient = ID_MAP.get(entry["ingredient_ref"], entry["ingredient_ref"])
        if ingredient not in inheritance or entry["archetype_ref"] != inheritance[ingredient]:
            raise ValueError("Invalid archetype reference")
        if entry["method_ref"] not in raw["cooking_methods"]:
            raise ValueError("Invalid method reference")
        if len(entry["steps"]) != len(ACTIONS[index]):
            raise ValueError("Every original step requires adaptation")
        if len(CHECKPOINTS[index]) != len(ACTIONS[index]):
            raise ValueError("Every adapted step requires a checkpoint")
        paths.append(
            {
                "ingredient_ref": ingredient,
                "method_ref": "boil_simmer" if ingredient == "grain_rice_arborio" else entry["method_ref"],
                "archetype_ref": entry["archetype_ref"],
                "title": entry["title"],
                "steps": ACTIONS[index],
                "checkpoints": CHECKPOINTS[index],
                "source_id": f"domain/recipe_paths/{index}",
            }
        )
    return {
        "sha256": hashlib.sha256(content).hexdigest(),
        "raw": raw,
        "inheritance": inheritance,
        "paths": paths,
    }
